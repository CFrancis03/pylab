import { createHash } from 'node:crypto'
import react from '@vitejs/plugin-react'
import { defineConfig, type Plugin } from 'vite'
import { PYODIDE_CACHE } from './src/offlineConstants.ts'

/**
 * Writes sw.js at build time. It precaches the app shell (every emitted file, so the build id changes
 * whenever any content hash does) and keeps the 13 MB Python runtime in a separate, long-lived cache,
 * so deploying an update never makes anyone download Python again.
 */
function offlineShell(): Plugin {
  let base = '/'
  return {
    name: 'offline-shell',
    apply: 'build',
    configResolved(config) {
      base = config.base
    },
    generateBundle(_options, bundle) {
      const emitted = Object.keys(bundle).sort()
      const build = createHash('sha1').update(emitted.join('|')).digest('hex').slice(0, 10)
      const precache = [...emitted, 'favicon.svg', 'manifest.webmanifest'].map((f) => base + f)
      const source = `// Generated by vite.config.ts. Do not edit.
const BASE = ${JSON.stringify(base)}
const SHELL = 'pylab-shell-${build}'
const PYODIDE = ${JSON.stringify(PYODIDE_CACHE)}
const PRECACHE = ${JSON.stringify([base, ...precache])}

self.addEventListener('install', (e) => {
  // No skipWaiting here: a waiting worker only takes over when the learner clicks "Reload to update".
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)))
})

self.addEventListener('activate', (e) => {
  e.waitUntil(
    (async () => {
      for (const k of await caches.keys()) if (k.startsWith('pylab-shell-') && k !== SHELL) await caches.delete(k)
      await self.clients.claim()
    })(),
  )
})

self.addEventListener('message', (e) => {
  if (e.data === 'SKIP_WAITING') self.skipWaiting()
})

async function cacheFirst(cacheName, request) {
  const hit = await caches.match(request)
  if (hit) return hit
  const res = await fetch(request)
  if (res.ok && res.status === 200) (await caches.open(cacheName)).put(request, res.clone())
  return res
}

async function pageWithFallback(request) {
  try {
    return await fetch(request)
  } catch {
    return (await caches.match(BASE + 'index.html')) || (await caches.match(BASE)) || Response.error()
  }
}

self.addEventListener('fetch', (e) => {
  const req = e.request
  const url = new URL(req.url)
  if (req.method !== 'GET' || url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return
  const path = url.pathname.slice(BASE.length)
  if (path.startsWith('pyodide/')) e.respondWith(cacheFirst(PYODIDE, req))
  else if (req.mode === 'navigate' || path === '' || path === 'index.html') e.respondWith(pageWithFallback(req))
  else e.respondWith(cacheFirst(SHELL, req))
})
`
      this.emitFile({ type: 'asset', fileName: 'sw.js', source })
    },
  }
}

// https://vite.dev/config/
export default defineConfig({
  // GitHub Pages serves a project site from /<repo>/, so the deploy workflow sets VITE_BASE=/pylab/.
  base: process.env.VITE_BASE ?? '/',
  plugins: [react(), offlineShell()],
  // Pyodide ships its own loader; pre-bundling it breaks asset resolution.
  optimizeDeps: { exclude: ['pyodide'] },
  worker: { format: 'es' },
  build: {
    rolldownOptions: {
      output: {
        // Stable vendor chunks cache across deploys, so an update only re-downloads our own code.
        codeSplitting: {
          groups: [
            { name: 'react', test: /node_modules[\\/](react|react-dom|scheduler)[\\/]/ },
            { name: 'zod', test: /node_modules[\\/]zod[\\/]/ },
            { name: 'codemirror', test: /node_modules[\\/](@codemirror|@lezer|style-mod|w3c-keyname|@marijn)[\\/]/ },
          ],
        },
      },
    },
  },
})
